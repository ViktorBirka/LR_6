// Завдання 1.1. Площа кола
{
  const radius = 5;
  const area = Math.PI * radius ** 2;
  console.log("Площа кола:", area.toFixed(2));
}

// Завдання 1.2. Площа прямокутника
{
  const length = 8;
  const width = 4;
  const area = length * width;
  console.log("Площа прямокутника:", area.toFixed(2));
}

// Завдання 1.3. Об’єм циліндра
{
  const radius = 3;
  const height = 7;
  const volume = Math.PI * radius ** 2 * height;
  console.log("Об’єм циліндра:", volume.toFixed(2));
}
